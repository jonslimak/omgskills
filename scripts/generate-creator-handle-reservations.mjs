#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(new URL("..", import.meta.url).pathname);
export const creatorRegistryPath = path.join(repoRoot, "index", "seeds", "creators.json");
export const generatedReservationsPath = path.join(
  repoRoot,
  "netlify",
  "functions",
  "_shared",
  "catalog-reserved-handles.ts",
);

const handlePattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

function normalizedHandle(value) {
  return String(value ?? "").trim().toLowerCase();
}

export function buildCreatorHandleReservations(registry) {
  if (!Array.isArray(registry?.creators)) {
    throw new Error("creators.json must contain a creators array");
  }

  const ownersByHandle = new Map();
  for (const entry of registry.creators) {
    const owner = normalizedHandle(entry?.handle);
    if (!owner) {
      throw new Error("Creator handle cannot be empty");
    }

    for (const rawHandle of [entry.handle, ...(entry.aliases ?? [])]) {
      const handle = normalizedHandle(rawHandle);
      if (!handlePattern.test(handle) || handle.length > 80) {
        throw new Error(`Invalid creator handle or alias: ${rawHandle}`);
      }

      const previousOwner = ownersByHandle.get(handle);
      if (previousOwner && previousOwner !== owner) {
        throw new Error(`Creator handle collision: ${handle} belongs to both ${previousOwner} and ${owner}`);
      }
      ownersByHandle.set(handle, owner);
    }
  }

  return [...ownersByHandle.keys()].sort((a, b) => a.localeCompare(b));
}

export function loadCreatorHandleReservations() {
  const registry = JSON.parse(readFileSync(creatorRegistryPath, "utf8"));
  return buildCreatorHandleReservations(registry);
}

export function assertStaticProfileHandlesReserved(collections, reservedHandles) {
  const reserved = new Set(reservedHandles.map(normalizedHandle));
  for (const collection of collections) {
    if (collection?.type !== "author" || !collection.authorHandle) continue;
    if (!reserved.has(normalizedHandle(collection.authorHandle))) {
      throw new Error(
        `Static profile handle is not reserved: ${collection.authorHandle}. Add it to index/seeds/creators.json first.`,
      );
    }
  }
}

export function renderCreatorHandleReservations(handles) {
  const values = handles.map((handle) => `  ${JSON.stringify(handle)},`).join("\n");
  return `// Generated by scripts/generate-creator-handle-reservations.mjs. Do not edit.\n\nexport const catalogReservedProfileHandles = new Set([\n${values}\n]);\n`;
}

export function expectedCreatorHandleReservationsSource() {
  return renderCreatorHandleReservations(loadCreatorHandleReservations());
}

function main() {
  const expected = expectedCreatorHandleReservationsSource();
  if (process.argv.includes("--check")) {
    let actual = "";
    try {
      actual = readFileSync(generatedReservationsPath, "utf8");
    } catch {
      // The stale error below includes the repair command.
    }
    if (actual !== expected) {
      throw new Error(
        "Creator handle reservations are stale. Run npm run generate:creator-handle-reservations.",
      );
    }
    console.log("Creator handle reservations are current");
    return;
  }

  writeFileSync(generatedReservationsPath, expected);
  console.log(`Generated ${path.relative(repoRoot, generatedReservationsPath)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
